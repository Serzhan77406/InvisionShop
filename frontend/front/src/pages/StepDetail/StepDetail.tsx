const defaultExtendedData = {
  fullDesc: "Детальная юридическая информация по данному этапу находится на согласовании с экспертами по градостроительству РК.",
  docs: ["Заявление на оказание услуги", "Удостоверение личности гражданина РК"],
  laws: "Законодательство Республики Казахстан в сфере архитектуры и градостроительства"
};

export const StepDetail: React.FC = () => {
  const { id } = useParams<{ id: string }>();
  const navigate = useNavigate();
  const [step, setStep] = useState<Step | null>(null);
  const [loading, setLoading] = useState<boolean>(true);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    api.get<Step>(`/steps/${id}/`)
      .then((response) => {
        setStep(response.data);
        setLoading(false);
      })
      .catch((err) => {
        console.error(err);
        setError('Не удалось загрузить информацию о шаге. Возможно, он ещё не создан экспертом.');
        setLoading(false);
      });
  }, [id]);

  if (loading) return <div className="loading-spinner">Загрузка деталей этапа...</div>;
  if (error || !step) return <div className="error-message-box">⚠️ {error || 'Данные для этого шага отсутствуют.'}</div>;

  const currentExtendedData = stepExtendedData[step.id] || defaultExtendedData;

  return (
    <div className="step-detail-page">
      <button onClick={() => navigate('/steps')} className="btn-back">
        &larr; Вернуться к списку 7 шагов
      </button>

      <div className="step-detail-card">
        <div className="step-detail-header">
          <span className="step-detail-badge">Этап №{step.id}</span>
          <span className={`status-tag ${step.is_completed ? 'completed' : 'pending'}`}>
            {step.is_completed ? '✅ Этап успешно пройден' : '⏳ Требует выполнения / Ожидайте проверки'}
          </span>
        </div>

        <h1 className="step-detail-title">{step.title}</h1>
        
        <div className="detail-section">
          <h2>Описание этапа (Регламент РК)</h2>
          <p className="full-description">{currentExtendedData.fullDesc}</p>
        </div>

        <div className="detail-section">
          <h2>Необходимые документы</h2>
          <ul className="documents-list">
            {currentExtendedData.docs.map((doc, idx) => (
              <li key={idx}>📄 {doc}</li>
            ))}
          </ul>
        </div>

        <div className="detail-section laws-section">
          <h2>Нормативно-правовая база РК</h2>
          <p className="laws-text"><strong>Правовое основание:</strong> {currentExtendedData.laws}</p>
          <Link to="/laws" className="laws-link-stub">
            Перейти к законодательным актам РК в разделе «Законы» &rarr;
          </Link>
        </div>
      </div>
    </div>
  );
};